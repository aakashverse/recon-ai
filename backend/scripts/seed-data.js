export async function seedDatabase() {
  console.log('[Seeder] Initializing database connection...');
  await connectDB();

  console.log('[Seeder] Cleaning existing collections...');
  await Promise.all([
    Invoice.deleteMany({}),
    RuleCache.deleteMany({}),
    BankLedger.deleteMany({}),
    ReconciliationEvent.deleteMany({}),
    JournalEntry.deleteMany({}),
  ]);
  await resetChainPointer();

  console.log(`[Seeder] Inserting ${SAMPLE_INVOICES.length} realistic enterprise B2B Invoices...`);
  await Invoice.insertMany(SAMPLE_INVOICES);

  console.log(`[Seeder] Inserting ${SAMPLE_RULES.length} Tier-2 Historical Vendor Pattern Rules...`);
  await RuleCache.insertMany(SAMPLE_RULES);

  // Write sample batch JSON for CLI benchmark & UI consumption
  const batchFilePath = path.join(__dirname, 'sample-batch-50.json');
  fs.writeFileSync(batchFilePath, JSON.stringify(SAMPLE_BANK_FEED_50, null, 2));
  console.log(`[Seeder] Exported ${SAMPLE_BANK_FEED_50.length} stress-test bank transactions to ${batchFilePath}`);

  console.log('✅ [Seeder] High-Difficulty Database seeding completed successfully.');
}

// Run directly if called from CLI
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  seedDatabase()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error('❌ [Seeder Failed]:', err);
      process.exit(1);
    });
}
